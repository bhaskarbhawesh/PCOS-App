import { useState } from 'react';
import { Alert, Text, View } from 'react-native';

import { Body, Button, Card, Chip, Divider, Heading, Screen, Small } from '../../components/ui';
import { formatDayLong, today } from '../../lib/dates';
import { METRIC_LABELS, summarize } from '../../lib/report';
import { CHECK_IN_METRICS } from '../../lib/types';
import { sharePdfReport } from '../../services/export';
import { useStore } from '../../state/store';
import { space, useTheme } from '../../theme';

const RANGES = [30, 60, 90] as const;

export default function ReportScreen() {
  const t = useTheme();
  const { data } = useStore();
  const [range, setRange] = useState<(typeof RANGES)[number]>(30);
  const [busy, setBusy] = useState(false);
  const summary = summarize(data, today(), range);

  const share = async () => {
    setBusy(true);
    try {
      await sharePdfReport(data, summary);
    } catch {
      Alert.alert('Couldn’t create the PDF', 'Please try again. If it keeps happening, contact support.');
    } finally {
      setBusy(false);
    }
  };

  return (
    <Screen>
      <Body>A clear summary of your habits, check-ins and cycle log to bring to an appointment. You choose where it goes.</Body>
      <View style={{ flexDirection: 'row', gap: space.s }}>
        {RANGES.map((r) => (
          <Chip key={r} label={`${r} days`} selected={range === r} onPress={() => setRange(r)} />
        ))}
      </View>

      <Card>
        <Heading>Preview</Heading>
        <Small>
          {formatDayLong(summary.start)} – {formatDayLong(summary.end)}
        </Small>
        <Divider />
        <Text style={{ color: t.text, fontSize: 15, fontWeight: '600' }}>Habits</Text>
        {summary.habits.length === 0 ? (
          <Small>No habits scheduled in this period.</Small>
        ) : (
          summary.habits.map((h) => (
            <View key={h.habitId} style={{ flexDirection: 'row', justifyContent: 'space-between', gap: space.s }}>
              <Body style={{ flex: 1 }}>{h.name}</Body>
              <Body muted>
                {h.completed} / {h.scheduled}
              </Body>
            </View>
          ))
        )}
        <Divider />
        <Text style={{ color: t.text, fontSize: 15, fontWeight: '600' }}>Check-ins: {summary.checkInCount}</Text>
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: space.m }}>
          {CHECK_IN_METRICS.map((m) => (
            <Small key={m}>
              {METRIC_LABELS[m]}: {summary.averages[m] ?? '–'}
            </Small>
          ))}
        </View>
        <Divider />
        <Text style={{ color: t.text, fontSize: 15, fontWeight: '600' }}>Cycle entries: {summary.cycleCount}</Text>
      </Card>

      <Button title={busy ? 'Preparing…' : 'Share PDF'} icon="share-outline" onPress={share} disabled={busy} />
      <Small>Generated by Compite. For personal tracking only; not medical advice.</Small>
    </Screen>
  );
}
